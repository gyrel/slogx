// ID is an opaque identifier generated by the caller, never free-form text.
type ID string

// Hash is a caller-provided digest or fingerprint.
type Hash string

// Host is a policy target hostname.
type Host string

// Standard holds optional correlation attributes. Nil fields are omitted.
type Standard struct {
	OpID       *ID
	ReqID      *ID
	SandboxID  *ID
	Generation *uint64
	DurationMS *uint64
	ErrorCode  *ID
}

// Event is a validated catalog record.
type Event struct {
	level slog.Level
	name  string
	attrs []slog.Attr
}

// Level returns the catalog level.
func (e Event) Level() slog.Level { return e.level }

// Name returns the canonical event name.
func (e Event) Name() string { return e.name }

// Attrs returns a copy of the event attributes, including optional standard fields.
func (e Event) Attrs(s Standard) []slog.Attr {
	a := append([]slog.Attr(nil), e.attrs...)
	if s.OpID != nil {
		a = append(a, slog.String("op_id", string(*s.OpID)))
	}
	if s.ReqID != nil {
		a = append(a, slog.String("req_id", string(*s.ReqID)))
	}
	if s.SandboxID != nil {
		a = append(a, slog.String("sandbox_id", string(*s.SandboxID)))
	}
	if s.Generation != nil {
		a = append(a, slog.Uint64("generation", *s.Generation))
	}
	if s.DurationMS != nil {
		a = append(a, slog.Uint64("duration_ms", *s.DurationMS))
	}
	if s.ErrorCode != nil {
		a = append(a, slog.String("error_code", string(*s.ErrorCode)))
	}
	return a
}

// Emit writes this event using the standard slog handler path.
func (e Event) Emit(ctx context.Context, logger *slog.Logger, standard Standard) {
	logger.LogAttrs(ctx, e.level, e.name, e.Attrs(standard)...)
}

var errInvalid = errors.New("events: invalid catalog value")

func valid(v string, choices ...string) bool {
	for _, c := range choices {
		if v == c {
			return true
		}
	}
	return false
}
func build(name, component string, outcome Outcome, level slog.Level, attrs ...slog.Attr) Event {
	// Catalog membership of literal names is enforced by the test suite
	// (TestConstructorsAndDocs + FuzzCanonicalEventName); a library must not
	// panic (AGENTS §5).
	a := make([]slog.Attr, 4, 4+len(attrs))
	a[0] = slog.Int("schema_version", 1)
	a[1] = slog.String("event", name)
	a[2] = slog.String("component", component)
	a[3] = slog.String("outcome", string(outcome))
	return Event{level: level, name: name, attrs: append(a, attrs...)}
}

